// Generate src/features/system/config-hints.gen.ts from the kernel's annotated
// config/default.toml (the source of truth for what every key means).
//
//   node scripts/generate-config-hints.mjs            # reads ../agos
//   AGOS_DIR=/path/to/agos node scripts/generate-config-hints.mjs
//
// The REST API serves config values with no documentation, so the panel's Config
// page vendors these one-line hints. Re-run after a kernel config change.
import { readFileSync, writeFileSync } from "node:fs";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const agos = resolve(root, process.env.AGOS_DIR ?? "../agos");
const toml = readFileSync(`${agos}/config/default.toml`, "utf8");

const MAX = 300;
const hints = new Map();
const sectionHints = new Map();
let table = "";
let buf = [];
let exampleBlock = false;

for (const raw of toml.split("\n")) {
  const line = raw.trim();
  if (!line) {
    buf = [];
    continue;
  }
  const section = line.match(/^\[([^[\]]+)\]$/);
  if (section) {
    table = section[1];
    // The block above a [table] header documents the whole table — the fallback
    // for keys the file leaves uncommented.
    const doc = buf.join(" ").trim();
    if (doc) sectionHints.set(table, clamp(doc));
    buf = [];
    exampleBlock = false;
    continue;
  }
  if (line.startsWith("#")) {
    const text = line.replace(/^#\s?/, "").trim();
    // Banner rules: "--- Runaway-task containment ---".
    if (/^-{3,}/.test(text)) continue;
    // A commented-out *table* header starts an example block ("[agent_budget.
    // overrides.researcher]"); the keys under it belong to that table, not the
    // one we're in, so don't attribute them at all.
    if (/^\[[^[\]]+\]$/.test(text)) {
      exampleBlock = true;
      continue;
    }
    // A commented-out assignment is a key left at its built-in default — the
    // comment block above it is that key's doc, and the key still shows up in
    // the live tree. Record it and reset, or its doc leaks onto the next key.
    // Lowercase-only: prose like "Empty = same-origin only" is not a key.
    const commented = text.match(/^([a-z][a-z0-9_.-]*)\s*=\s*\S/);
    if (commented) {
      // Inside an example block the assignment is illustration, not a key: skip
      // it without disturbing the prose, which documents the enclosing table.
      if (exampleBlock) continue;
      record(commented[1], buf.join(" ").trim());
      buf = [];
      continue;
    }
    if (text) buf.push(text);
    continue;
  }
  exampleBlock = false;
  const kv = line.match(/^([A-Za-z0-9_.]+)\s*=\s*(.*)$/);
  if (!kv) continue;
  const inline = kv[2].match(/#\s*(.+?)\s*$/);
  record(kv[1], buf.join(" ").trim() || (inline ? inline[1] : ""));
  buf = [];
}

function record(key, hint) {
  if (!hint) return;
  hints.set(table ? `${table}.${key}` : key, clamp(hint));
}

function clamp(text) {
  return text.length > MAX ? `${text.slice(0, MAX - 1).trimEnd()}…` : text;
}

const out = `// AUTO-GENERATED by scripts/generate-config-hints.mjs from the kernel's
// config/default.toml. Do not edit — re-run \`npm run generate:config-hints\`.
// The REST API serves config values without documentation; these are the
// operator-facing descriptions for the Config page.

export const CONFIG_HINTS: Record<string, string> = {
${entries(hints)}
};

/** Doc block above a \`[table]\` header — the fallback for its uncommented keys. */
export const CONFIG_SECTION_HINTS: Record<string, string> = {
${entries(sectionHints)}
};
`;

writeFileSync(`${root}/src/features/system/config-hints.gen.ts`, out);
console.log(
  `wrote src/features/system/config-hints.gen.ts (${hints.size} keys, ${sectionHints.size} sections)`,
);

function entries(map) {
  return [...map]
    .sort(([a], [b]) => a.localeCompare(b))
    .map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`)
    .join("\n");
}
