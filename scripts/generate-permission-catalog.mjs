// Generate src/features/agents/permission-catalog.gen.ts from the kernel's tool
// manifests (`[capabilities_required]` in ../agos/tools/**/*.toml) — the source
// of truth for which resources an agent can be granted.
//
//   node scripts/generate-permission-catalog.mjs            # reads ../agos
//   AGOS_DIR=/path/to/agos node scripts/generate-permission-catalog.mjs
//
// The REST API has no "list every grantable permission" endpoint: `GET /tools`
// only reports what is *installed*. The Grant dialog merges the live list with
// this vendored one so an operator can grant a resource ahead of the tool that
// needs it. Re-run after adding or changing a core tool.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { resolve, dirname, basename } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const agos = resolve(root, process.env.AGOS_DIR ?? "../agos");

function* tomlFiles(dir) {
  for (const e of readdirSync(dir, { withFileTypes: true })) {
    const p = `${dir}/${e.name}`;
    if (e.isDirectory()) yield* tomlFiles(p);
    else if (e.name.endsWith(".toml")) yield p;
  }
}

/** resource -> { bits, tools:Set } */
const catalog = new Map();

for (const file of tomlFiles(`${agos}/tools`)) {
  const toml = readFileSync(file, "utf8");
  const block = toml.match(/\[capabilities_required\]([\s\S]*?)(?=\n\[|$)/);
  if (!block) continue;
  const tool = toml.match(/^\s*name\s*=\s*"([^"]+)"/m)?.[1] ?? basename(file, ".toml");
  for (const perm of block[1].matchAll(/"([^"]+):([rwxqo]+)"/g)) {
    const [, resource, bits] = perm;
    const entry = catalog.get(resource) ?? { bits: "", tools: new Set() };
    entry.bits = [..."rwxqo"].filter((c) => entry.bits.includes(c) || bits.includes(c)).join("");
    entry.tools.add(tool);
    catalog.set(resource, entry);
  }
}

const rows = [...catalog]
  .sort(([a], [b]) => a.localeCompare(b))
  .map(
    ([resource, e]) =>
      `  { resource: ${JSON.stringify(resource)}, bits: ${JSON.stringify(e.bits)}, tools: ${JSON.stringify([...e.tools].sort())} },`,
  )
  .join("\n");

const out = `// AUTO-GENERATED by scripts/generate-permission-catalog.mjs from the kernel's
// tool manifests. Do not edit — re-run \`npm run generate:permissions\`.
// \`GET /tools\` only lists *installed* tools; this is every resource the shipped
// tools can ask for, so the Grant dialog can show the full set.

export interface KnownPermission {
  resource: string;
  /** Union of the bits the tools below require. */
  bits: string;
  /** Core tools that declare this resource. */
  tools: string[];
}

export const KNOWN_PERMISSIONS: KnownPermission[] = [
${rows}
];
`;

writeFileSync(`${root}/src/features/agents/permission-catalog.gen.ts`, out);
console.log(`wrote src/features/agents/permission-catalog.gen.ts (${catalog.size} resources)`);

// The operator-facing one-liners are hand-written (the manifests carry none);
// flag any new resource that arrived without one.
const hintsFile = readFileSync(`${root}/src/features/agents/permission-catalog.ts`, "utf8");
const hintBlock = hintsFile.match(/const RESOURCE_HINTS[^{]*{([\s\S]*?)\n};/)?.[1] ?? "";
const described = new Set([...hintBlock.matchAll(/"([^"]+)":/g)].map((m) => m[1]));
const undescribed = [...catalog.keys()].filter((r) => !described.has(r));
if (undescribed.length > 0) {
  console.warn(
    `warning: no RESOURCE_HINTS entry for ${undescribed.length} resource(s): ${undescribed.join(", ")}`,
  );
}
